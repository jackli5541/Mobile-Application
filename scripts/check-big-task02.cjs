const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

async function main() {
  const output = path.resolve(__dirname, '../docs/experiment2/screenshots')
  fs.mkdirSync(output, { recursive: true })
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto(process.env.EXPERIMENT_URL || 'http://localhost:9010/#/big-task02', { waitUntil: 'domcontentloaded' })
    const rows = page.locator('.article-item')
    await rows.last().waitFor()
    assert.equal(await rows.count(), 10)
    await page.getByText('李亚鸿 24211860108', { exact: true }).waitFor()
    assert.equal(await page.locator('main .q-list > .article-item').count(), 10)
    await page.screenshot({ path: path.join(output, '01-desktop-list.png'), fullPage: true })
    const like = page.getByRole('button', { name: '点赞文章 0', exact: true })
    const stars = Number((await like.innerText()).replace(/\D/g, ''))
    await like.click()
    assert.equal(Number((await like.innerText()).replace(/\D/g, '')), stars + 1)
    assert.equal(await page.getByRole('status').count(), 0)
    await page.screenshot({ path: path.join(output, '02-like.png'), fullPage: true })
    const original = await rows.first().locator('.q-item__label').first().innerText()
    const timestamp = await rows.first().locator('.q-item__label--caption').innerText()
    await page.getByRole('button', { name: '编辑文章 0', exact: true }).click()
    await page.getByLabel('Title', { exact: true }).fill('Cancelled draft')
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    assert.equal(await rows.first().locator('.q-item__label').first().innerText(), original)
    await page.getByRole('button', { name: '编辑文章 0', exact: true }).click()
    await page.getByLabel('Title', { exact: true }).fill('  Edited article title  ')
    await page.screenshot({ path: path.join(output, '03-edit-dialog.png') })
    await page.getByRole('button', { name: 'OK', exact: true }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    assert.equal(await rows.first().locator('.q-item__label').first().innerText(), 'Edited article title')
    assert.notEqual(await rows.first().locator('.q-item__label--caption').innerText(), timestamp)
    await page.screenshot({ path: path.join(output, '04-edited.png'), fullPage: true })
    await page.getByRole('button', { name: '删除文章 0', exact: true }).click()
    assert.equal(await rows.count(), 9)
    assert.equal(await page.getByRole('status').count(), 0)
    await page.screenshot({ path: path.join(output, '05-deleted.png'), fullPage: true })
    await rows.first().click()
    await page.getByRole('status').waitFor()
    await page.screenshot({ path: path.join(output, '06-click-message.png'), fullPage: true })
    await page.getByRole('status').waitFor({ state: 'hidden' })
    const search = page.getByLabel('Search', { exact: true })
    await search.fill('not-an-existing-article')
    await page.getByText('No articles', { exact: true }).waitFor()
    await page.screenshot({ path: path.join(output, '07-empty-search.png') })
    await search.fill('[')
    await page.getByText('No articles', { exact: true }).waitFor()
    await search.fill('')
    await page.getByRole('button', { name: '刷新文章', exact: true }).click()
    assert.equal(await rows.count(), 10)
    for (const width of [600, 599, 390, 320]) {
      await page.setViewportSize({ width, height: 844 })
      await page.waitForTimeout(350)
      assert.equal(await page.locator('main .q-card.article-item').count(), width < 600 ? 10 : 0)
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      if (width === 390) {
        await page.screenshot({ path: path.join(output, '08-mobile-cards.png'), fullPage: true })
        await page.getByRole('button', { name: '编辑文章 0', exact: true }).click()
        await page.getByLabel('Title', { exact: true }).fill('Mobile edited title')
        await page.screenshot({ path: path.join(output, '09-mobile-dialog.png') })
        await page.getByLabel('Title', { exact: true }).press('Enter')
        await page.getByRole('dialog').waitFor({ state: 'hidden' })
        assert.ok((await rows.first().innerText()).includes('Mobile edited title'))
      }
    }
    assert.deepEqual(errors, [])
    console.log('PASS: responsive breakpoints, no horizontal overflow, like, delete, click isolation, cancel, save, timestamp, trim, Enter, search and refresh.')
  } finally {
    await browser.close()
  }
}
main().catch((error) => { console.error(error); process.exitCode = 1 })

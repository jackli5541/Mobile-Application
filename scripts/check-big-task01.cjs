// 使用已安装的 Playwright，或通过 PLAYWRIGHT_MODULE 指定其绝对模块路径。
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

async function main() {
  const output = path.resolve(__dirname, '../docs/experiment1/screenshots')
  fs.mkdirSync(output, { recursive: true })
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto(process.env.EXPERIMENT_URL || 'http://localhost:9000/#/big-task01')
    const rows = page.locator('.article-item')
    await rows.last().waitFor()
    assert.equal(await rows.count(), 10)
    assert.ok(await page.getByText('李亚鸿 24211860108', { exact: true }).isVisible())
    await page.screenshot({ path: path.join(output, '01-main-mobile.png'), fullPage: true })
    await rows.first().click()
    await page.getByRole('status').filter({ hasText: 'Item for id=0' }).waitFor()
    await page.screenshot({ path: path.join(output, '02-click-message.png'), fullPage: true })
    await page.getByRole('status').filter({ hasText: 'Item for id=0' }).waitFor({ state: 'hidden' })
    const like = page.getByRole('button', { name: '点赞文章 0', exact: true })
    await like.click()
    assert.match(await like.innerText(), /1/)
    assert.equal(await page.getByText('Item for id=0', { exact: false }).count(), 0)
    await page.screenshot({ path: path.join(output, '03-like.png'), fullPage: true })
    const input = page.getByLabel('搜索标题或作者', { exact: true })
    await input.fill('ONLINE')
    await page.getByText('共 10 篇文章，当前显示 2 篇').waitFor()
    assert.equal(await rows.count(), 2)
    await page.screenshot({ path: path.join(output, '04-title-search.png'), fullPage: true })
    await input.fill('Tom3')
    await page.getByText('共 10 篇文章，当前显示 1 篇').waitFor()
    assert.equal(await rows.count(), 1)
    await input.press('Enter')
    await page.getByRole('button', { name: '搜索文章', exact: true }).click()
    await page.screenshot({ path: path.join(output, '05-author-search.png'), fullPage: true })
    await input.fill('[')
    await page.getByText('No articles · 没有匹配的文章').waitFor()
    assert.equal(await rows.count(), 0)
    await page.screenshot({ path: path.join(output, '06-empty-search.png'), fullPage: true })
    await page.getByRole('button', { name: '清空搜索', exact: true }).click()
    await page.getByText('共 10 篇文章，当前显示 10 篇').waitFor()
    await like.click()
    await page.getByRole('button', { name: '刷新文章', exact: true }).click()
    assert.match(await like.innerText(), /0/)
    await input.fill('Tom3')
    await page.getByRole('button', { name: '刷新文章', exact: true }).click()
    assert.equal(await input.inputValue(), 'Tom3')
    assert.equal(await rows.count(), 1)
    await page.getByRole('button', { name: '清空搜索', exact: true }).click()
    assert.equal(await input.getAttribute('maxlength'), '60')
    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 900 })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow at ${width}px`)
    }
    await page.screenshot({ path: path.join(output, '07-main-desktop.png'), fullPage: true })
    await page.getByRole('link', { name: '大实验一：文章搜索与组件封装', exact: false }).click()
    assert.ok(page.url().endsWith('#/big-task01'))
    await page.goto('http://localhost:9000/#/chapter102/task102')
    const styleButton = page.getByRole('button', { name: 'Change Style', exact: true })
    await styleButton.waitFor()
    await styleButton.click()
    assert.ok(await styleButton.evaluate((button) => button.classList.contains('bg-primary')))
    for (let index = 0; index < 6; index += 1) await styleButton.click()
    assert.ok(await styleButton.evaluate((button) => button.classList.contains('bg-info')))
    assert.deepEqual(errors, [])
    console.log('PASS: 初始列表、身份信息、点击与自动消失、点赞及冒泡隔离、标题与作者筛选、搜索事件、特殊字符、清空、刷新、maxlength、侧栏路由、320/390/768/1440px无横向溢出、无页面异常。')
  } finally {
    await browser.close()
  }
}

main().catch((error) => { console.error(error); process.exitCode = 1 })
